for (const billId of Object.keys(HARD_PATCHES)) {
  const fp = path.join(billsDir, `${billId}.json`);
  const bill = JSON.parse(fs.readFileSync(fp, "utf8"));
  const patch = HARD_PATCHES[billId];
  const idx = bill.bill_contents.findIndex(
    (c) => c.difficulty_level === "hard",
  );
  const title =
    bill.bill_contents.find((c) => c.difficulty_level === "normal")?.title ??
    bill.name;

  const hardEntry = {
    id:
      idx >= 0
        ? bill.bill_contents[idx].id
        : crypto.randomUUID(),
    bill_id: billId,
    difficulty_level: "hard",
    title,
    summary: patch.summary,
    content: patch.content,
    created_at:
      idx >= 0 ? bill.bill_contents[idx].created_at : now,
    updated_at: now,
  };

  if (idx >= 0) {
    bill.bill_contents[idx] = hardEntry;
  } else {
    bill.bill_contents.push(hardEntry);
  }

  bill.updated_at = now;
  fs.writeFileSync(fp, `${JSON.stringify(bill, null, 2)}\n`, "utf8");
}

