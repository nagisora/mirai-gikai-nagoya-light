for (const [billId, patch] of Object.entries(PATCHES)) {
  const fp = path.join(billsDir, `${billId}.json`);
  const bill = JSON.parse(fs.readFileSync(fp, "utf8"));

  const hardIdx = bill.bill_contents.findIndex(
    (c) => c.difficulty_level === "hard",
  );
  const normalIdx = bill.bill_contents.findIndex(
    (c) => c.difficulty_level === "normal",
  );

  if (hardIdx >= 0) {
    bill.bill_contents[hardIdx] = {
      ...bill.bill_contents[hardIdx],
      summary: patch.hard.summary,
      content: patch.hard.content,
      updated_at: now,
    };
  }

  if (normalIdx >= 0) {
    bill.bill_contents[normalIdx] = {
      ...bill.bill_contents[normalIdx],
      summary: patch.normal.summary,
      content: patch.normal.content,
      updated_at: now,
    };
  } else {
    bill.bill_contents.push({
      id: randomUUID(),
      bill_id: billId,
      difficulty_level: "normal",
      title: bill.name,
      summary: patch.normal.summary,
      content: patch.normal.content,
      created_at: now,
      updated_at: now,
    });
  }

  bill.updated_at = now;
  fs.writeFileSync(fp, `${JSON.stringify(bill, null, 2)}\n`, "utf8");
}

